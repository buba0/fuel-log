declare(strict_types=1);

function language(?string $requested = null): string
{
    static $current = 'en';
    if ($requested !== null) {
        $current = $requested === 'pl' ? 'pl' : 'en';
    }

    return $current;
}

function set_language(string $code): void
{
    language($code);
}

function t(string $text, array $params = []): string
{
    if (language() === 'pl') {
        $text = polish_strings()[$text] ?? $text;
    }

    if ($params === []) {
        return $text;
    }

    $replacements = [];
    foreach ($params as $key => $value) {
        $replacements['{' . $key . '}'] = (string) $value;
    }

    return strtr($text, $replacements);
}

function localized_decimal(float $value, int $places = 2): string
{
    return language() === 'pl'
        ? number_format($value, $places, ',', "\u{00A0}")
        : number_format($value, $places, '.', ',');
}

function localized_date(string $date, string $format = 'j M Y'): string
{
    $value = (new DateTimeImmutable($date))->format($format);
    if (language() !== 'pl') {
        return $value;
    }

    return strtr($value, [
        'Jan' => 'sty',
        'Feb' => 'lut',
        'Mar' => 'mar',
        'Apr' => 'kwi',
        'May' => 'maj',
        'Jun' => 'cze',
        'Jul' => 'lip',
        'Aug' => 'sie',
        'Sep' => 'wrz',
        'Oct' => 'paź',
        'Nov' => 'lis',
        'Dec' => 'gru',
    ]);
}

